<script setup>
import { computed, defineAsyncComponent, onBeforeUnmount, onMounted, ref, watch } from 'vue'
import { RouterLink, useRouter } from 'vue-router'
import CitySearch from '../components/CitySearch.vue'
import Icon3D from '../components/Icon3D.vue'
import { aqiCategory, categoryStyle } from '../lib/aqi'
import { tilt as vTilt } from '../lib/tilt'

// Three.js is large; load it only for the landing page hero.
const HeroScene3D = defineAsyncComponent(() => import('../components/landing/HeroScene3D.vue'))

const router = useRouter()
const reducedMotion = typeof window !== 'undefined'
  && window.matchMedia('(prefers-reduced-motion: reduce)').matches

function openCity(place) {
  router.push({
    name: 'dashboard',
    query: { city: place.name, region: place.region || undefined, lat: place.lat, lon: place.lon },
  })
}

// ---------- live snapshot (ticker + counters) ----------
const snapshot = ref(null)
onMounted(async () => {
  try {
    const res = await fetch('/api/snapshot')
    if (res.ok) snapshot.value = await res.json()
  } catch { /* the page still works without live numbers */ }
})

const delhi = computed(() => snapshot.value?.cities.find((c) => c.name === 'New Delhi'))

// ---------- smog vision ----------
const smog = ref(0)
const smogLabel = computed(() => (smog.value ? aqiCategory(smog.value) : 'Clean air'))
const smogStyle = computed(() => categoryStyle(smog.value ? aqiCategory(smog.value) : 'Good'))
const smogPresets = computed(() => {
  const live = (snapshot.value?.cities || [])
    .filter((c) => ['New Delhi', 'Ludhiana'].includes(c.name))
    .map((c) => ({ label: `${c.name.replace('New ', '')} now`, aqi: c.aqi }))
  return [{ label: 'Clean', aqi: 0 }, ...live, { label: 'Severe day', aqi: 450 }]
})

// Count-up for the fire stat, once it is both on screen and loaded.
const statsEl = ref(null)
const statsVisible = ref(false)
const shownFires = ref(null) // null = show the real number (no animation yet)
let io = null
let raf = 0

onMounted(() => {
  io = new IntersectionObserver(([entry]) => {
    if (entry.isIntersecting) { statsVisible.value = true; io.disconnect() }
  }, { threshold: 0.4 })
  io.observe(statsEl.value)
})

watch([statsVisible, () => snapshot.value?.fires_48h_punjab_haryana], ([visible, target]) => {
  if (!visible || target == null) return
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    shownFires.value = target
    return
  }
  const start = performance.now()
  const step = (t) => {
    const p = Math.min((t - start) / 1200, 1)
    shownFires.value = Math.round(target * (1 - (1 - p) ** 3)) // ease-out
    if (p < 1) raf = requestAnimationFrame(step)
  }
  raf = requestAnimationFrame(step)
})

onBeforeUnmount(() => { io?.disconnect(); cancelAnimationFrame(raf) })

// ---------- content ----------
const FEATURES = [
  { icon: 'fire', title: 'Smoke Trail & Radar', section: 'smoke', view: 'radar',
    text: 'Trace your air back 48 hours, or watch a time-lapse of fires, wind and smoke drifting across North India.' },
  { icon: 'wind_face', title: 'Incoming Smoke Alert', section: 'smoke', view: 'coming',
    text: 'Runs today\'s satellite-detected fires forward on forecast winds to estimate when smoke may reach your city.' },
  { icon: 'school', title: 'School Mode + parent notices', section: 'school',
    text: 'UrbanWise guidance (go, limit or cancel) for assembly, PE and dismissal — and a notice to parents in English, Hindi and Punjabi.' },
  { icon: 'face_with_medical_mask', title: 'Today\'s air & forecast', section: '',
    text: 'India\'s CPCB AQI scale applied to CAMS model estimates, plain-language advice, and the best and worst hours to be outside.' },
  { icon: 'lungs', title: 'Your exposure', section: 'health',
    text: 'How much pollution you\'ll breathe in, shown as a cigarette equivalent — plus when to open windows.' },
  { icon: 'speech_balloon', title: 'Ask UrbanWise', section: 'ask',
    text: 'Ask by voice or text, in English, हिंदी or ਪੰਜਾਬੀ — and hear the answer read aloud.' },
]

const STEPS = [
  { icon: 'satellite', title: 'Satellites & sensors', text: 'NASA fire detections, CAMS air-quality forecasts and wind data, refreshed hourly.' },
  { icon: 'chart_increasing', title: 'UrbanWise connects them', text: 'CPCB-scale AQI, smoke back- and forward-tracking, and School Mode guidance based on CPCB categories.' },
  { icon: 'school', title: 'You act', text: 'Clear decisions for today and tomorrow — and a notice ready to send.' },
