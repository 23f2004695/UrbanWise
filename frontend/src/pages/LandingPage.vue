Principal, Green Valley Public School`,
  hi: `प्रिय अभिभावकगण,

9 अक्टूबर 2026 को, हम अस्थमा या सांस की समस्याओं वाले बच्चों की अतिरिक्त देखभाल के साथ सामान्य समय-सारणी का पालन करेंगे।

कृपया सुनिश्चित करें कि आपका बच्चा अपना इनहेलर साथ रखे और आज पर्याप्त पानी पिए।

प्रिंसिपल, ग्रीन वैली पब्लिक स्कूल`,
